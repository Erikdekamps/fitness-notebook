// Builds the one-file app: bundles src/js, inlines the CSS and writes index.html.
//
//   node build.mjs           write index.html
//   node build.mjs --check   fail when index.html is not what the sources build (used in CI)

import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const TEMPLATE = 'src/index.template.html';
const OUTPUT = 'index.html';
const NOTE = '<!-- Built from src/ by "npm run build". Do not edit this file: change src/ and build again. -->';

/** The app's JavaScript as one script, with every module bundled in. */
async function bundleScript() {
  const result = await build({
    entryPoints: ['src/js/app.js'],
    bundle: true,
    format: 'iife',
    target: ['safari14', 'chrome90', 'firefox90'],
    charset: 'utf8',
    legalComments: 'none',
    write: false,
  });
  return result.outputFiles[0].text.trimEnd();
}

/** The whole page: template + CSS + script. */
async function buildPage() {
  const [template, font, styles, script] = await Promise.all([
    readFile(TEMPLATE, 'utf8'),
    readFile('src/font.css', 'utf8'),
    readFile('src/styles.css', 'utf8'),
    bundleScript(),
  ]);
  const css = `${styles.trimEnd()}\n\n${font.trimEnd()}`;
  // Function replacers, so "$" in the CSS or script is never read as a pattern.
  return template
    .replace('<!doctype html>', () => `<!doctype html>\n${NOTE}`)
    .replace('/*__CSS__*/', () => css)
    .replace('/*__JS__*/', () => script);
}

const page = await buildPage();

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (current !== page) {
    console.error(`${OUTPUT} is out of date. Run "npm run build" and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  await writeFile(OUTPUT, page);
  console.log(`Wrote ${OUTPUT} (${Math.round(page.length / 1024)} kB).`);
}
